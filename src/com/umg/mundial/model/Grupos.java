package com.umg.mundial.model;

public class Grupos {
    private int id_Grupos;
    private String nombre;

    public Grupos() {}

    // Getters y Setters
    public int getIdGrupo() { return id_Grupos; }
    public void setIdGrupo(int id_Grupos) { this.id_Grupos = id_Grupos; }

    public String getNombre() { return nombre; }
    public void setNombre(String nombre) { this.nombre = nombre; }
}
